import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

// PDFKit already depends on fontkit; no font parser is shipped to the browser.
const require = createRequire(import.meta.resolve("pdfkit"));
const { create } = require("fontkit");
const font = create(await readFile(new URL("../node_modules/@vexflow-fonts/bravura/bravura.otf", import.meta.url)));
const license = await readFile(new URL("../node_modules/@vexflow-fonts/bravura/LICENSE.txt", import.meta.url), "utf8");
const symbols = await readFile(new URL("../src/renderer/smufl.ts", import.meta.url), "utf8");
const outlines = Object.fromEntries([...symbols.matchAll(/&#x([\dA-F]+);/g)].map((match) => {
  const codePoint = parseInt(match[1], 16);
  const glyph = font.glyphForCodePoint(codePoint);
  if (!glyph.id) throw new Error(`Missing Bravura glyph ${match[0]}`);
  return [String.fromCodePoint(codePoint), { path: glyph.path.toSVG(), advanceWidth: glyph.advanceWidth }];
}));
await writeFile(new URL("../src/renderer/smufl-outlines.ts", import.meta.url),
  `// Generated by pnpm run fonts:outlines from the bundled Bravura font.\n` +
  `// These glyph outlines retain the font's license below.\n/*\n${license.trim()}\n*/\n\n` +
  `export const SMUFL_UNITS_PER_EM = ${font.unitsPerEm};\n` +
  `export const SMUFL_OUTLINES: Record<string, { path: string; advanceWidth: number }> = ${JSON.stringify(outlines, null, 2)};\n`);
console.log(`Generated ${Object.keys(outlines).length} SMuFL glyph outlines.`);
