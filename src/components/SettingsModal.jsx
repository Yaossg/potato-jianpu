export default function SettingsModal({
  isOpen,
  onClose,
  instrument,
  onInstrumentChange,
  volume,
  onVolumeChange,
  omitInitialRest,
  onOmitInitialRestChange,
  sampleRate,
  onSampleRateChange,
}) {
  if (!isOpen) return null;

  return (
    <div className="settings-modal-overlay">
      <div className="settings-modal">
        <div className="settings-header">
          <h3>Settings</h3>
          <button className="close-button" onClick={onClose}>✕</button>
        </div>
        <div className="settings-content">
          <div className="settings-group">
            <label htmlFor="instrument-select">Instrument:</label>
            <select
              id="instrument-select"
              value={instrument}
              onChange={onInstrumentChange}
            >
              {GMInstruments.map(inst => inst.name).map((inst, index) => (
                <option key={index} value={index}>
                  {inst}
                </option>
              ))}
            </select>
          </div>

          <div className="settings-group">
            <label htmlFor="volume-slider">Volume:</label>
            <span className="volume-value">{volume}%</span>
            <input
              id="volume-slider"
              type="range"
              min="0"
              max="200"
              value={volume}
              onChange={onVolumeChange}
            />
          </div>

          <div className="settings-group">
            <label htmlFor="omit-initial-rest">Whether to omit initial rest:</label>
            <input
              id="omit-initial-rest"
              type="checkbox"
              checked={omitInitialRest}
              onChange={onOmitInitialRestChange}
            />
          </div>

          <div className="settings-group">
            <label htmlFor="sample-rate">Export Sample Rate:</label>
            <input
              id="sample-rate"
              type="number"
              value={sampleRate}
              onChange={onSampleRateChange}
            />
          </div>
        </div>
      </div>
    </div>
  );
}